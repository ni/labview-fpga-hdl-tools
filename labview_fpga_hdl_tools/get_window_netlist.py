# Generated flat wrapper file produced by the GetWindowNetlist TCL script.
_WINDOW_FLAT_WRAPPER_FILE = "TheLvWindowFlatWrapper.v"

# =============================================================================
# HACK: per-family lists of LabVIEW-generated files that gen-window pulls from
# the export's NIProtectedFiles folder.
#
# These vary by target family (for example, PkgLvFpgaConst.vhd only exists in
# FlexRIO exports, and cRIO names its constraints file after the top level), so
# they do NOT belong in the tool. Refactor this out into nihdlsettings.py (for
# example, config.add_lv_window_generated_file(...) and
# config.set_lv_window_constraints_source(...)) and delete this table.
# Until then, every new target family needs an entry here.
# =============================================================================
_LV_GENERATED_FILES_BY_FAMILY = {
    "FlexRIO": {
        "files": [
            "CodeGenerationResults.lvtxt",
            "PkgLvFpgaConst.vhd",
            "PkgCommIntConfiguration.vhd",
            "PkgDmaPortCommIfcRegs.vhd",
            "PkgDmaPortDmaFifos.vhd",
        ],
        "constraints_xdc": "constraints.xdc",
    },
    "CompactRIO": {
        "files": [
            "CodeGenerationResults.lvtxt",
            "PkgCommIntConfiguration.vhd",
            "PkgDmaPortCommIfcRegs.vhd",
            "PkgDmaPortDmaFifos.vhd",
        ],
        "constraints_xdc": "toplevel_gen.xdc",
    },
}


def _get_lv_generated_files(target_family):
    """Return the HACK per-family gen-window file settings (see _LV_GENERATED_FILES_BY_FAMILY).

    Raises:
        ValueError: If the target family has no entry.
    """
    try:
        return _LV_GENERATED_FILES_BY_FAMILY[target_family]
    except KeyError:
        raise ValueError(
            f"gen-window does not know which LabVIEW-generated files to copy for target "
            f"family '{target_family}'. Supported families: "
            f"{', '.join(_LV_GENERATED_FILES_BY_FAMILY)}."
        ) from None


def _write_window_netlist_wrapper_tcl(config, get_netlist_tcl_path):
    """Write a TCL wrapper that adds the export's encrypted .vhe sources, then runs the target TCL.

    Vivado Project Export leaves Vivado-encrypted ``.vhe`` files (e.g. the cRIO sideband
    packages) in ``NIProtectedFiles`` but does not add them to the XPR, so synthesis of the
    window fails on the missing units.

    Returns:
        str: Path to the wrapper TCL script.
    """
    project_export_base = os.path.dirname(
        os.path.dirname(os.path.abspath(config.lv_window_vivado_project_export_xpr))
    )
    protected_files_folder = os.path.join(project_export_base, "NIProtectedFiles")
    vhe_files = sorted(glob.glob(os.path.join(protected_files_folder, "*.vhe")))
    if vhe_files:
        reporter.detail(
            f"Adding {len(vhe_files)} encrypted .vhe file(s) from {protected_files_folder}"
        )

    def tcl_path(path):
        return "{" + path.replace("\\", "/") + "}"

    lines = ["# Generated by nihdl gen-window"]
    lines.append(f"set nihdl_vhe_files [list {' '.join(tcl_path(f) for f in vhe_files)}]")
    lines.append("foreach f $nihdl_vhe_files {")
    lines.append(
        "  if {[llength [get_files -quiet $f]] == 0} { add_files -norecurse -fileset sources_1 $f }"
    )
    lines.append("}")
    lines.append(
        "if {[llength $nihdl_vhe_files]} { set_property FILE_TYPE VHDL [get_files $nihdl_vhe_files] }"
    )
    lines.append(f"source {tcl_path(get_netlist_tcl_path)}")

    wrapper_folder = os.path.join(config.root_dir, "objects", "TCL")
    os.makedirs(wrapper_folder, exist_ok=True)
    wrapper_path = os.path.join(wrapper_folder, "GetWindowNetlistWrapper.tcl")
    with open(wrapper_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return wrapper_path


def _get_window_netlist(config):
    """Gets the Window netlist from the Vivado Project as well as other HDL Files."""
    get_netlist_tcl_path = os.path.abspath(
        os.path.join(config.vivado_tcl_scripts_folder, "GetWindowNetlist.tcl")
    )
    reporter.detail(f"Using TCL script at: {get_netlist_tcl_path}")

    # Extract project directory and name from the XPR path
    vivado_project_path = os.path.dirname(
        os.path.abspath(config.lv_window_vivado_project_export_xpr)
    )
    project_name = os.path.splitext(os.path.basename(config.lv_window_vivado_project_export_xpr))[0]

    reporter.detail(f"Vivado project path: {vivado_project_path}")
    reporter.detail(f"Vivado project name: {project_name}")

    # Determine Vivado executable from either direct executable path or tools dir.
    vivado_executable = common.get_vivado_executable(config.vivado_tools_folder)
    if not vivado_executable:
        raise ValueError("Unable to resolve Vivado executable from configuration")

    vivado_abs = os.path.abspath(vivado_executable)
    if not config.skip_vivado and not os.path.exists(vivado_abs):
        raise FileNotFoundError(
            f"Vivado executable not found at: {vivado_abs}\n"
            f"Please check your --vivado argument or VivadoToolsFolder setting in nihdlsettings.py"
        )

    source_file = os.path.join(vivado_project_path, _WINDOW_FLAT_WRAPPER_FILE)
    destination_folder = config.lv_window_netlist_output_folder

    # Create destination directory if it doesn't exist
    os.makedirs(destination_folder, exist_ok=True)

    # In skip_vivado mode, skip running Vivado
    if config.skip_vivado:
        reporter.detail("SKIP VIVADO: Skipping Vivado execution")

        # Create a mock Verilog netlist file if it doesn't exist
        if not os.path.exists(source_file):
            with open(source_file, "w") as f:
                f.write("// Mock Verilog netlist file created for testing\n")
            reporter.detail(f"Created mock Verilog netlist file for testing: {source_file}")
    else:
        # Remove any stale netlist from a previous run so that the post-run
        # existence check below cannot be satisfied by leftover output. Without
        # this, a failed Vivado run would still look like a success.
        if os.path.exists(source_file):
            os.remove(source_file)
            reporter.detail(f"Removed stale netlist file: {source_file}")

        wrapper_tcl_path = _write_window_netlist_wrapper_tcl(config, get_netlist_tcl_path)

        try:
            common.run_command(
                [
                    vivado_abs,
                    f"{project_name}.xpr",
                    "-mode",
                    "batch",
                    "-source",
                    wrapper_tcl_path,
                ],
                cwd=vivado_project_path,
                capture_output=False,
                check=True,
            )
        except subprocess.CalledProcessError as e:
            raise RuntimeError(
                f"Vivado exited with a non-zero status ({e.returncode}) while extracting the "
                f"Window netlist. Synthesis or netlist generation likely failed; review the "
                f"Vivado output above and vivado.log for details."
            ) from e

        # Check for success marker in vivado.log file
        vivado_log_path = os.path.join(vivado_project_path, "vivado.log")
        if not os.path.exists(vivado_log_path):
            raise RuntimeError("Vivado log file not found. TCL script execution may have failed.")

        try:
            with open(vivado_log_path, "r", encoding="utf-8", errors="replace") as log_file:
                log_content = log_file.read()
        except OSError as e:
            raise RuntimeError(f"Failed to read Vivado log file: {e}") from e

        # This GET_WINDOW=FAILED constant is set in the GetWindowNetlist.tcl file
        # We have not found a better way to surface an error from Vivado executing a
        # TCL script up to Python
        if "GET_WINDOW=FAILED" in log_content:
            raise RuntimeError("Window netlist extraction failed. See vivado.log for details.")

        # Check if the expected output file was generated
        if not os.path.exists(source_file):
            raise RuntimeError(
                f"Vivado TCL script execution failed: Expected output file {source_file} was not generated."
            )

    destination_file = os.path.join(destination_folder, _WINDOW_FLAT_WRAPPER_FILE)

    if not os.path.exists(source_file):
        raise FileNotFoundError(f"Source file {source_file} not found")
    try:
        shutil.copy(source_file, destination_file)
    except OSError as e:
        raise RuntimeError(f"Failed to copy {source_file} to {destination_file}: {e}") from e
    reporter.detail(f"Copied {source_file} to {destination_file}")


def _copy_lv_generated_files(config):
    """Copy files that are generated by LV into TheWindow folder for use in the HDL vivado flow.

    Returns:
        bool: True if all files were copied successfully, False if any file was
        missing or could not be copied.
    """
    # Extract the parent directory path from the XPR path
    # The NIProtectedFiles folder is typically at the same level as VivadoProject
    project_export_base = os.path.dirname(
        os.path.dirname(config.lv_window_vivado_project_export_xpr)
    )
    protected_files_folder = os.path.join(project_export_base, "NIProtectedFiles")

    files_to_copy = _get_lv_generated_files(config.target_family)["files"]

    success = True
    for file_name in files_to_copy:
        source_file = os.path.join(protected_files_folder, file_name)
        destination_file = os.path.join(config.lv_window_netlist_output_folder, file_name)

        try:
            if os.path.exists(source_file):
                shutil.copy(source_file, destination_file)
                reporter.detail(f"Copied {source_file} to {destination_file}")
            else:
                reporter.error(f"Error: Source file {source_file} not found")
                success = False
        except Exception as e:
            reporter.error(f"Error copying file: {str(e)}")
            success = False

    return success


def _extract_lv_window_constraints(config):
    """Extract LabVIEW FPGA constraints from the export's constraints XDC.

    This function finds the constraints section marked with BEGIN_LV_FPGA_CONSTRAINTS and
    END_LV_FPGA_CONSTRAINTS in the family's constraints XDC (see
    _LV_GENERATED_FILES_BY_FAMILY), and creates a separate file
    containing just those constraints in the Window folder, excluding the marker lines.

    Args:
        config (CommandConfiguration): Configuration settings object

    Raises:
        FileNotFoundError: If the NIProtectedFiles constraints XDC does not exist
    """
    # Extract the parent directory path from the XPR path
    # The NIProtectedFiles folder is typically at the same level as VivadoProject
    project_export_base = os.path.dirname(
        os.path.dirname(config.lv_window_vivado_project_export_xpr)
    )
    protected_files_folder = os.path.join(project_export_base, "NIProtectedFiles")

    constraints_xdc = _get_lv_generated_files(config.target_family)["constraints_xdc"]
    source_file = os.path.join(protected_files_folder, constraints_xdc)
    destination_folder = config.lv_window_netlist_output_folder
    destination_file = os.path.join(destination_folder, "TheWindowConstraints.xdc")

    # Make sure destination folder exists
    os.makedirs(destination_folder, exist_ok=True)

    # Extract constraints between markers
    if not os.path.exists(source_file):
        raise FileNotFoundError(f"Source file {source_file} not found")

    # Exports can contain Windows-1252 comment art (e.g. 0xAF); normalize to UTF-8 for downstream tools.
    with open(source_file, "rb") as f_in:
        raw = f_in.read()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        text = raw.decode("latin-1")
    lines = text.splitlines(keepends=True)

    # Find the marker lines
    start_idx = None
    end_idx = None

    for i, line in enumerate(lines):
        if "# BEGIN_LV_FPGA_CONSTRAINTS" in line:
            start_idx = i
        if "# END_LV_FPGA_CONSTRAINTS" in line:
            end_idx = i
            break

    # Check if markers were found
    if start_idx is None or end_idx is None:
        reporter.warn(f"Warning: Could not find constraint markers in {constraints_xdc}")
        return

    # Extract the constraints EXCLUDING the marker lines
    lv_constraints = lines[start_idx + 1 : end_idx]

    # Write the constraints to the destination file
    with open(destination_file, "w", encoding="utf-8", newline="") as f_out:
        f_out.writelines(lv_constraints)

    reporter.success(f"Successfully extracted LV FPGA constraints to {destination_file}")


def _validate_ini(config):
    """Validate that all required configuration settings are present.

    This function checks that all settings required for getting window netlist
    are present in the configuration object and validates that paths exist.

    Args:
        config: Configuration object containing settings from INI file

    Raises:
        ValueError: If any required settings are missing or paths are invalid
    """
    missing_settings = common.collect_missing_settings(
        config,
        [
            ("lv_window_netlist_output_folder", "LVWindowNetlistSettings.LVWindowFolder"),
            ("target_family", "GeneralSettings.TargetFamily"),
        ],
    )
    invalid_paths = []

    if config.target_family and config.target_family not in _LV_GENERATED_FILES_BY_FAMILY:
        invalid_paths.append(
            f"GeneralSettings.TargetFamily - gen-window supports "
            f"{', '.join(_LV_GENERATED_FILES_BY_FAMILY)}: {config.target_family}"
        )

    # Check required paths for window netlist generation
    if not config.lv_window_vivado_project_export_xpr:
        missing_settings.append("LVWindowNetlistSettings.LVWindowVivadoProjectExportXPR")
    else:
        # Validate that the XPR file exists
        invalid_path = common.validate_path(
            config.lv_window_vivado_project_export_xpr,
            "LVWindowNetlistSettings.LVWindowVivadoProjectExportXPR",
            "file",
        )
        if invalid_path:
            invalid_paths.append(invalid_path)
        if not config.skip_vivado:
            # Check that the project folder path length does not exceed 80 characters
            # OK to skip this check in skip_vivado mode because we are not running Vivado
            vivado_project_path = os.path.dirname(config.lv_window_vivado_project_export_xpr)
            if len(vivado_project_path) > 80:
                raise ValueError(
                    f"Error: Vivado project path exceeds 80 characters ({len(vivado_project_path)} chars).\n"
                    f"Path: {vivado_project_path}\n"
                    f"Vivado has issues with long paths. Please use a shorter path for your project."
                )

    # Check for Vivado tools path
    if not config.vivado_tools_folder:
        missing_settings.append("VivadoProjectSettings.VivadoToolsFolder")
    else:
        # Validate Vivado setting as either tools dir or executable path.
        invalid_path = common.validate_vivado_setting(
            config.vivado_tools_folder,
            "VivadoProjectSettings.VivadoToolsFolder",
        )
        if invalid_path:
            invalid_paths.append(invalid_path)

    error = common.build_settings_error(missing_settings, invalid_paths)
    if error:
        raise ValueError(error)


def get_window(config=None):
    """Main entry point for the script."""
    # Load configuration
    if config is None:
        config = CommandConfiguration()

    # Validate that all required settings are present
    try:
        _validate_ini(config)
    except Exception as e:
        reporter.error(f"Error: {e}")
        return 1

    try:
        _get_window_netlist(config)
    except Exception as e:
        reporter.error(f"Error: {e}")
        return 1
    if not _copy_lv_generated_files(config):
        reporter.error("Error: Failed to copy one or more LabVIEW-generated files.")
        return 1
    try:
        _extract_lv_window_constraints(config)
    except Exception as e:
        reporter.error(f"Error extracting constraints: {e}")
        return 1

    reporter.success("Window netlist extraction completed successfully.")

    reporter.success("\n" + "=" * 80)
    reporter.success("NOTICE: If you have already created a Vivado project, you must run")
    reporter.success(
        '         "nihdl create-project --update" to pull in the latest Window netlist files.'
    )
    reporter.success("=" * 80)

    return 0
