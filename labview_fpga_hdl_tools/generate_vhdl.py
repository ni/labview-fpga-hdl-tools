"""Generated VHDL file generation.

Renders the project's generated VHDL sources from Mako templates. This is the
single batch used by the Vivado (synthesis) and ModelSim (simulation) flows as
well as LabVIEW FPGA target-plugin generation, so the window VHDL, the
PkgNiHdlSettings package, the Board IO signal-assignments example, and any
future generated design sources are all produced together and stay consistent.

This logic lives in its own module (rather than alongside target-plugin
generation) because it is also used by workflows that are not about generating a
LabVIEW FPGA target plugin, such as the standalone ``gen-hdl`` command and the
Vivado/ModelSim project flows.
"""

