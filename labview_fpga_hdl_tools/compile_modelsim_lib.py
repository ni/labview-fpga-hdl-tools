"""Compile the Xilinx ModelSim/Questa simulation libraries (unisim, secureip, ...).

This wraps Vivado's ``compile_simlib`` so that HDL simulation can run on any
machine without the NI build tools. The compiled libraries are written to the
folder configured as ``xilinx_sim_lib_folder`` and are later mapped into
``modelsim.ini`` by ``gen-modelsim``.

The compiled libraries are simulator- and platform-specific, so they cannot be
committed to source control and must be built on the machine where the
simulation runs. Compilation is slow, so this command is idempotent: if the
requested libraries already exist it returns immediately unless ``--force`` is
passed.
"""

